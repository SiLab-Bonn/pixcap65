def perform_initial_total_measurement(cli_args):
    """
    perform_initial_total_measurement(cli_args)

    @author: Dominik Fischer
    last update: 2026-08-28

    CHECK: verify completeness of this docstring
    Initializes the setup for a total cap measurement and performs one without applying any bias voltage.
    After completing the measurement a backup of the output file will be created by appending `_1`.

    :param cli_args: namespace of the command-line arguments provided. The namespace could be generated by :py:mod:`argparse`.
        Otherwise a object with similar attributes needs to be provided.
    """
    global scan_configuration
    with get_lock():
        scan_configuration[ScanConfigurationKeys.AVERAGE_MEASUREMENTS] = 40
        scan_configuration[ScanConfigurationKeys.FREQUENCY_RANGE] = np.arange(1, cli_args.maximum_full_scan_freq, cli_args.full_scan_freq_step)

    if cli_args.total_unbiased:
        print("Will perform the unbiased total cap scan.")
        with PixCapSetup(scan_configuration, cli_args.output_file, measurement=PixcapMeasurements.TOTAL_CAPACITANCE) as pix:
            pix.pixcap.frequency_settling = cli_args.freq_settle
            # FIXME: depending on the setup binary readout will not work.
            with pix.binary_readout_mode() as binary_pix:
                binary_pix.scan(data_group_spec="unbiased_full")

    with get_lock():
        del scan_configuration[ScanConfigurationKeys.AVERAGE_MEASUREMENTS]
        try:
            time.sleep(cli_args.wait)
            if cli_args.total_unbiased:
                shutil.copyfile(cli_args.output_file, cli_args.output_file.replace(".h5", "_1.h5"))
        except:
            pass


def perform_iv_measurement(cli_args):
    """
    perform_iv_measurement(cli_args)

    @author: Dominik Fischer
    last update: 2026-08-28

    Initializes the setup for an investigation of the leakage currents dependence on the applied voltage.
    For this measurement the sensor is to be operated in reverse bias.
    For this measurement where only the leakage currents are measured it is encouraged to use multiple current
    measurements to enhance the overall accuracy of the results.
    After completing the measurement a backup of the output file will be created by appending `_2`.

    :param cli_args: namespace of the command-line arguments provided. The namespace could be generated by :py:mod:`argparse`.
        Otherwise a object with similar attributes needs to be provided.
    """
    global scan_configuration
    with get_lock():
        scan_configuration[ScanConfigurationKeys.BIAS_VOLTAGE_RANGE] = -1 * np.arange(0, cli_args.maximum_hv_voltage, cli_args.hv_step)
        scan_configuration[ScanConfigurationKeys.BIAS_AVERAGE_MEASUREMENTS] = 20
        assert np.all(0 >= scan_configuration[ScanConfigurationKeys.BIAS_VOLTAGE_RANGE])
    if cli_args.iv_flag:
        print("Perform IV Scan.")
        with PixCapSetup(scan_configuration, cli_args.output_file, measurement=PixcapMeasurements.TOTAL_CAPACITANCE) as pix:
            pix.bias_scan(data_group_spec="I_V_Characteristic")

    with get_lock():
        del scan_configuration[ScanConfigurationKeys.BIAS_AVERAGE_MEASUREMENTS]
        try:
            time.sleep(cli_args.wait)
            if cli_args.iv_flag:
                shutil.copyfile(cli_args.output_file, cli_args.output_file.replace(".h5", "_2.h5"))
        except:
            pass


def perform_coarse_cv_scan(cli_args, hv_range):
    """
    perform_coarse_cv_scan(cli_args, hv_range)

    @author: Dominik Fischer
    last update: 2026-08-28

    Implements a coarse cv scan suitable for only a few pixel to decide on the spacings to be used for a more fine scan
    in order to determine the depletion voltage on a per pixel level.

    The voltages of the CV characterization are to be supplied by the commandline arguments Namespace object.
    For each of these voltages (should be a coarse grid) the few selected pixel are scanned for their capacitances.
    The switching frequencies used for determining the capacitances are to be supplied by the cli namespace.

    Only reversed bias voltage grids are allowed.
    After completing the measurement a backup of the output file will be created by appending `_3`.


    :param cli_args: namespace of the command-line arguments provided. The namespace could be generated by :py:mod:`argparse`.
        Otherwise a object with similar attributes needs to be provided.
    :param hv_range: UNUSED PARAMETER? The range seems to be completely specified by the GLOBAL scan configuration!
    """
    global scan_configuration

    with get_lock():
        assert np.all(scan_configuration[ScanConfigurationKeys.BIAS_VOLTAGE_RANGE] < 0)

    if cli_args.cv_general_flag and cli_args.cv_coarse_flag:
        print("Perform the coarse bias scan")
        with PixCapSetup(scan_configuration, cli_args.output_file, measurement=PixcapMeasurements.TOTAL_CAPACITANCE) as pix:
            pix.combined_bias_cv_scan(data_group_spec="C_V_Characteristic")

    with get_lock():
        try:
            time.sleep(cli_args.wait)
            if cli_args.cv_general_flag and cli_args.cv_coarse_flag:
                shutil.copyfile(cli_args.output_file, cli_args.output_file.replace(".h5", "_3.h5"))
        except:
            pass


def perform_fine_cv_scan(cli_args, hv_range):
    """
    perform_fine_cv_scan(cli_args, hv_range)

    @author: Dominik Fischer
    last update: 2026-08-28

    Implements a fine-grain cv scan suitable for a large pixel matrix
    in order to determine the depletion voltage on a per pixel level.

    The voltages of the CV characterization are to be supplied by the parameters to allow more flexibility with the spacing.
    For each of these voltages selected pixel are scanned for their capacitances.
    The switching frequencies used for determining the capacitances are to be supplied by the cli namespace.
    The scanned pixels are fixed from row 10 to row 35 and column 10 to column 35.

    Only reversed bias voltage grids are allowed.
    After completing the measurement a backup of the output file will be created by appending `_4`.

    :param cli_args: namespace of the command-line arguments provided. The namespace could be generated by :py:mod:`argparse`.
        Otherwise a object with similar attributes needs to be provided.
    :param hv_range: grid of the high voltages to use for the measurement.
    """
    global scan_configuration

    with get_lock():
        scan_configuration[ScanConfigurationKeys.BIAS_VOLTAGE_RANGE] = hv_range
        scan_configuration.update(start_row=10, stop_row=35, start_column=10, stop_column=35)
        scan_configuration[ScanConfigurationKeys.FREQUENCY_RANGE] = np.arange(1, cli_args.maximum_cv_freq, cli_args.cv_freq_step)
        assert np.all(scan_configuration[ScanConfigurationKeys.BIAS_VOLTAGE_RANGE] < 0)

    if cli_args.cv_general_flag and cli_args.cv_fine_flag:
        print("Perform the fine bias scan")
        with PixCapSetup(scan_configuration, cli_args.output_file, measurement=PixcapMeasurements.TOTAL_CAPACITANCE) as pix:
            pix.frequency_settling = cli_args.freq_settle
            pix.combined_bias_cv_scan(data_group_spec="C_V_Characteristic_refined")

    with get_lock():
        try:
            time.sleep(cli_args.wait)
            if cli_args.cv_general_flag and cli_args.cv_fine_flag:
                shutil.copyfile(cli_args.output_file, cli_args.output_file.replace(".h5", "_4.h5"))
        except:
            pass


def perform_biased_total_cap(cli_args):
    """
    perform_biased_total_cap(cli_args)

    @author: Dominik Fischer
    last update: 2026-08-28

    CHECK: Verify this docstring.
    Initializes the setup for a total cap measurement and performs one with applying a bias voltage
    suitable to completely deplete the investigated sensor.
    The actually applied bias voltage must be in reversed bias and sufficient to fully deplete the sensor.
    After completing the measurement a backup of the output file will be created by appending `_5`.

    :param cli_args: namespace of the command-line arguments provided. The namespace could be generated by :py:mod:`argparse`.
        Otherwise a object with similar attributes needs to be provided.
    """
    global scan_configuration
    with get_lock():
        if ScanConfigurationKeys.BIAS_VOLTAGE_RANGE in scan_configuration:
            del scan_configuration[ScanConfigurationKeys.BIAS_VOLTAGE_RANGE]
        scan_configuration.update(start_row=1, stop_row=41, start_column=0, stop_column=40, bias=-1 * cli_args.hv_voltage,
                                  average_measurements=40)
        scan_configuration[ScanConfigurationKeys.FREQUENCY_RANGE] = np.arange(1, cli_args.maximum_full_scan_freq, cli_args.full_scan_freq_step)
        scan_configuration[ScanConfigurationKeys.AVERAGE_MEASUREMENTS] = 30
        assert scan_configuration[ScanConfigurationKeys.BIAS_VOLTAGE_SINGLE] <= 0

    if cli_args.depleted_flag:
        print("Perform the full over-depleted scan.")
        with PixCapSetup(scan_configuration, cli_args.output_file, measurement=PixcapMeasurements.TOTAL_CAPACITANCE) as pix:
            pix.pixcap.frequency_settling = cli_args.freq_settle
            with pix.binary_readout_mode() as binary_pix:
                binary_pix.scan(data_group_spec="biased_{}_V_full".format(cli_args.hv_voltage))

    with get_lock():
        try:
            time.sleep(cli_args.wait)
            if cli_args.depleted_flag:
                shutil.copyfile(cli_args.output_file, cli_args.output_file.replace(".h5", "_5.h5"))
        except:
            pass
        finally:
            del scan_configuration[ScanConfigurationKeys.AVERAGE_MEASUREMENTS]


def perform_inter_pix_scan(cli_args):
    """
    perform_inter_pix_scan(cli_args)

    @author: Dominik Fischer
    last update: 2026-08-28

    Implements two inter-pixel capacitance scans.
    In both cases the the summed-up contributions of all eight neighbouring pixels to the inter-pixel capacitance is
    measured.

    The arguments must be submitted by the commandline arguments namespace object.
    These will also define whether only (and which one) or both inter-pixel capacitance measurements should be performed.
    The first inter-pixel capacitance measurement will be performed without applying a bias voltage.
    The second one will apply a reversed bias voltage.
    The bias voltage should be chosen sufficiently large to fully deplete the investigated sensor.


    :param cli_args: namespace of the command-line arguments provided. The namespace could be generated by :py:mod:`argparse`.
        Otherwise a object with similar attributes needs to be provided.
    """
    global scan_configuration

    with get_lock():
        scan_configuration[ScanConfigurationKeys.FREQUENCY_RANGE] = np.around(np.arange(1, cli_args.maximum_inter_pix_freq, cli_args.inter_pix_freq_step), 2)
        scan_configuration.update(start_row=2, stop_row=38, start_column=1, stop_column=38)
        if ScanConfigurationKeys.BIAS_VOLTAGE_SINGLE in scan_configuration:
            del scan_configuration[ScanConfigurationKeys.BIAS_VOLTAGE_SINGLE]

    if cli_args.inter_pix_cap:
        with PixCapSetup(scan_configuration, cli_args.output_file, measurement=PixcapMeasurements.INTER_CAPACITANCE) as pix:
            with pix.enhanced_readout_mode():
                pix.frequency_settling = cli_args.freq_settle
                pix.scan(data_group_spec="inter_unbiased_full")

    with get_lock():
        try:
            time.sleep(cli_args.wait)
            if cli_args.inter_pix_cap:
                shutil.copyfile(cli_args.output_file, cli_args.output_file.replace(".h5", "_6.h5"))
        except:
            pass
        finally:
            scan_configuration[ScanConfigurationKeys.BIAS_VOLTAGE_SINGLE] = -1 * cli_args.hv_voltage
            assert scan_configuration[ScanConfigurationKeys.BIAS_VOLTAGE_SINGLE] <= 0

    if cli_args.inter_pix_cap:
        with PixCapSetup(scan_configuration, cli_args.output_file, measurement=PixcapMeasurements.INTER_CAPACITANCE) as pix:
            with pix.enhanced_readout_mode():
                pix.frequency_settling = cli_args.freq_settle
                pix.scan(data_group_spec="inter_biased_M_{}_V_full_Extended".format(cli_args.hv_voltage))

    with get_lock():
        try:
            time.sleep(cli_args.wait)
            if cli_args.inter_pix_cap:
                shutil.copyfile(cli_args.output_file, cli_args.output_file.replace(".h5", "_7.h5"))
        except:
            pass


