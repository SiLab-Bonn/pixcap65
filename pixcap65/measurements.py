def release_lock():
    """
    Release the lock and deinitialize the acquired lock to clear memory and prevent leakage of semaphore objects
    outside the process.
    """
    global lock
    if lock is not None:
        lock.acquire()
        lock.release()
        del lock
        lock = None

def get_lock():
    """
    Get a lock to synchronize the access to the scan configuration applied to make the script functions thread-safe.
    The lock will be defined as a global module level constant and needs correct handling when the thread or process
    ends.
    :return: acquired lock. (not already acquired but initialized)
    """
    global lock
    if lock is None:
        import threading
        import atexit
        lock = threading.RLock()
        atexit.register(release_lock)

    return lock


